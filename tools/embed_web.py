"""Regenerate the embedded page after editing web/index.html."""
from pathlib import Path
import json
import re
root = Path(__file__).resolve().parents[1]
html = (root / 'web/index.html').read_text(encoding='utf-8')
catalog = json.loads((root/'docs/command-catalog.json').read_text(encoding='utf-8'))
extra = 'const commandCatalog='+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+';\n'
extra += (root/'web/json-tools.js').read_text(encoding='utf-8')
html = re.sub(r'/\* JSON_TOOLS_START \*/.*?/\* JSON_TOOLS_END \*/',
              lambda _: '/* JSON_TOOLS_START */\n'+extra+'\n/* JSON_TOOLS_END */',html,flags=re.S)
(root/'web/index.html').write_text(html,encoding='utf-8')
assert ')HTML"' not in html
(root / 'src/Web_page.h').write_text(
    '// Generated by tools/embed_web.py. Edit web/index.html instead.\n'
    'static const char PROGMEM INDEX_HTML[] = R"HTML(\n' + html + '\n)HTML";\n',
    encoding='utf-8')
